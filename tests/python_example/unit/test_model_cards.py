"""Every example has its generated card: README.md in the python and cpp dirs, model.html and result.webp in
the python dir, and every relative link in them resolves. Cards are generated by DX AI Studio
(python -m dx_modelzoo.tools.export_dx_app_cards); edit the generator, not the files."""
from __future__ import annotations

import json
import re
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[3]
PY = PROJECT_ROOT / "src" / "python_example"
CPP = PROJECT_ROOT / "src" / "cpp_example"
_LINK = re.compile(r'\]\(([^)\s]+)\)|(?:href|src)="([^"]+)"')

# Variants that ship without a result.webp, and why.
NO_RESULT_IMAGE = {
    "clip-text_resnet50_77x512_openai": "no image result for a text encoder",
    "vit-l-p16_512x512_swag": "model too large to generate on the reference board",
}


def _registered():
    rows = json.loads((PROJECT_ROOT / "config" / "model_registry.json").read_text(encoding="utf-8"))
    return {r["variant"] for r in rows}


def _variants(tree):
    """Registered variant dirs; a source-only example (not in the registry, e.g. SCRFD500M_PPU) has no card."""
    registered = _registered()
    return sorted(p.parent for p in tree.glob("*/*/*/config.json") if p.parent.name in registered)


def test_every_python_example_has_a_card():
    missing = [str(d.relative_to(PROJECT_ROOT)) for d in _variants(PY)
               if not all((d / f).is_file() for f in ("README.md", "model.html"))]
    assert not missing, missing


def test_every_python_example_has_a_result_image_unless_allowed():
    missing = [str(d.relative_to(PROJECT_ROOT)) for d in _variants(PY)
               if d.name not in NO_RESULT_IMAGE and not (d / "result.webp").is_file()]
    assert not missing, missing


def test_every_cpp_example_has_a_readme():
    missing = [str(d.relative_to(PROJECT_ROOT)) for d in _variants(CPP) if not (d / "README.md").is_file()]
    assert not missing, missing


def test_relative_links_resolve():
    files = list(PY.glob("*/*/*/README.md")) + list(CPP.glob("*/*/*/README.md")) + \
        list(PY.glob("*/*/*/model.html")) + [PROJECT_ROOT / "MODELS.md"]
    broken = []
    for f in files:
        for a, b in _LINK.findall(f.read_text(encoding="utf-8")):
            target = a or b
            if not target.startswith(("http", "data:", "#", "mailto:")) and not (f.parent / target).exists():
                broken.append(f"{f.relative_to(PROJECT_ROOT)}: {target}")
    assert not broken, broken[:20]


def test_cards_open_offline():
    for f in PY.glob("*/*/*/model.html"):
        text = f.read_text(encoding="utf-8")
        assert not re.search(r'<(script|link|img|iframe)[^>]+(src|href)="https?://', text), f
